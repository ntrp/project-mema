#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MEDIA_DIR="$ROOT_DIR/.data/media/test-series"
DURATION="3"

for tool in ffmpeg ffprobe; do
	command -v "$tool" >/dev/null 2>&1 || {
		echo "Missing required tool: $tool" >&2
		exit 1
	}
done

write_episode() {
	local out="$1" language="$2"
	mkdir -p "$(dirname "$out")"
	ffmpeg -hide_banner -loglevel error -y \
		-f lavfi -i "color=c=white:s=640x360:r=24:d=$DURATION" \
		-f lavfi -i "anoisesrc=color=white:duration=$DURATION:sample_rate=48000:amplitude=0.02" \
		-map 0:v:0 -map 1:a:0 -t "$DURATION" \
		-c:v libx264 -preset ultrafast -pix_fmt yuv420p \
		-c:a aac -b:a 192k -ac 2 \
		-metadata:s:v:0 "title=Mock white video" \
		-metadata:s:a:0 "language=$language" \
		-metadata:s:a:0 "title=Mock white noise $language" \
		"$out"
}

write_srt() {
	cat >"$1" <<SRT
1
00:00:00,000 --> 00:00:01,000
Mock external subtitle: $2
SRT
}

rm -rf "$MEDIA_DIR"

STANDARD="$MEDIA_DIR/01-standard-season/Season 01"
write_episode "$STANDARD/Severance.2022.S01E01.480p.WEB-DL.AAC2.0.EN.mkv" eng
write_episode "$STANDARD/Severance.2022.S01E02.480p.WEB-DL.AAC2.0.EN.mkv" eng
printf '%s\n' 'Severance (2022), TMDB 95396' >"$MEDIA_DIR/01-standard-season/SERIES.txt"
printf '%s\n' '01-ok-embedded' >"$MEDIA_DIR/01-standard-season/MEMA_PROFILES.txt"

ANIME="$MEDIA_DIR/02-anime-absolute/Season 01"
write_episode "$ANIME/Cowboy.Bebop.1998.S01E01.480p.WEB-DL.AAC2.0.JA.mkv" jpn
write_episode "$ANIME/Cowboy.Bebop.1998.S01E02.480p.WEB-DL.AAC2.0.JA.mkv" jpn
write_srt "$ANIME/Cowboy.Bebop.1998.S01E01.480p.WEB-DL.AAC2.0.JA.eng.srt" 'Cowboy Bebop S01E01'
printf '%s\n' 'Cowboy Bebop (1998), AniDB 23' >"$MEDIA_DIR/02-anime-absolute/SERIES.txt"
printf '%s\n' '09-mixed-existing-external' >"$MEDIA_DIR/02-anime-absolute/MEMA_PROFILES.txt"

cat >"$MEDIA_DIR/README.md" <<'README'
# Test Series Fixtures

Generated by `scripts/restore-test-series.sh` and seeded by
`scripts/seeds/dev.test-series.sql`.

- `01-standard-season`: a standard TMDB season with two episodes.
- `02-anime-absolute`: an AniDB-backed anime with absolute numbering and an external subtitle.

All videos are white test clips, audio is generated white noise, and subtitles are mock data.
README

while IFS= read -r -d '' file; do
	ffprobe -v error -select_streams v:0 -show_entries stream=codec_type -of csv=p=0 "$file" | grep -qx video
	ffprobe -v error -select_streams a:0 -show_entries stream=codec_type -of csv=p=0 "$file" | grep -qx audio
done < <(find "$MEDIA_DIR" -type f -name '*.mkv' -print0)

echo "Restored test series under $MEDIA_DIR"
